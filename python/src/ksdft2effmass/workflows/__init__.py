"""Public calculator-independent scientific Workflow contracts.

The root namespace exports immutable scientific Task, Workflow, gate, activation,
composition, artifact-provenance, replayable WorkflowRun, and effect-free
colored-Petri-net adaptation contracts. Generic colored-Petri-net objects remain
public from :mod:`ksdft2effmass.petrinet.colored`. The former abbreviated
``ksdft2effmass.workflows.cpn`` compatibility package is retired and is not aliased
from this namespace.

WorkflowRun records represent software state and deterministic reconstruction only.
They do not invoke Tasks, execute calculations, authenticate authority, perform
external effects, persist data, or establish scientific validity.
"""

